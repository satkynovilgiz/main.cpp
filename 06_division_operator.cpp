// Demonstrates integer division and floating-point division.

#include <iostream>
using namespace std;

int main() {
    cout << "Integer division 13 / 5 = " << 13 / 5 << endl;
    cout << "Integer division 91 / 7 = " << 91 / 7 << endl;
    cout << "Floating division 13 / 5.0 = " << 13 / 5.0 << endl;
    cout << "Floating division 91.0 / 7 = " << 91.0 / 7 << endl;

    return 0;
}